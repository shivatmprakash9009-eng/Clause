// node scripts/build-tokens.mjs  → writes src/styles/tokens.css
import fs from 'node:fs';

const t = JSON.parse(fs.readFileSync('tokens.json', 'utf8'));
const leaves = (node, path = []) =>
  Object.entries(node).flatMap(([k, v]) => {
    if (k.startsWith('$')) return [];
    if (v && typeof v === 'object' && '$value' in v) return [[[...path, k], v.$value]];
    return leaves(v, [...path, k]);
  });
const resolve = (val, all) => val.replace(/\{([^}]+)\}/g, (_, p) => all.get(p) ?? (() => { throw new Error(`Unresolved token ${p}`); })());

const light = leaves(t.color, ['color']);
const dark = leaves(t.dark, ['color']);
const lightMap = new Map(light.map(([p, v]) => [p.join('.'), v]));

const cssVar = (p) => `--c-${p.slice(1).join('-')}`;
let out = '/* GENERATED by scripts/build-tokens.mjs — do not edit */\n:root {\n  color-scheme: light;\n';
for (const [p, v] of light) out += `  ${cssVar(p)}: ${resolve(v, lightMap)};\n`;
for (const [group, prefix] of [['radius', '--r'], ['shadow', '--sh'], ['container', '--w'], ['z', '--z'], ['dur', '--dur'], ['ease', '--e']])
  for (const [p, v] of leaves(t[group], [group])) out += `  ${prefix}-${p.slice(1).join('-')}: ${v};\n`;
for (const [p, v] of leaves(t.font, ['font'])) out += `  --f-${p.slice(1).join('-')}: ${v};\n`;
out += '}\n\n';

const darkBlock = dark.map(([p, v]) => `  ${cssVar(p)}: ${v};`).join('\n');
out += `[data-theme='dark'] {\n  color-scheme: dark;\n${darkBlock}\n}\n\n`;
out += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n    color-scheme: dark;\n${darkBlock.replace(/^/gm, '  ')}\n  }\n}\n\n`;

// Tailwind v4 theme bridge
out += '@theme inline {\n';
for (const [p] of light) out += `  --color-${p.slice(1).join('-')}: var(${cssVar(p)});\n`;
for (const [p] of leaves(t.radius, ['radius'])) out += `  --radius-${p.slice(1).join('-')}: var(--r-${p.slice(1).join('-')});\n`;
for (const [p] of leaves(t.shadow, ['shadow'])) out += `  --shadow-${p.slice(1).join('-')}: var(--sh-${p.slice(1).join('-')});\n`;
for (const [p] of leaves(t.font.size, ['font', 'size'])) out += `  --text-${p.slice(2).join('-')}: var(--f-size-${p.slice(2).join('-')});\n`;
out += '  --font-sans: var(--f-family-sans);\n  --ease-out-expo: var(--e-out-expo);\n  --ease-in-out: var(--e-in-out);\n}\n';

fs.mkdirSync('src/styles', { recursive: true });
fs.writeFileSync('src/styles/tokens.css', out);
console.log('tokens.css written');
